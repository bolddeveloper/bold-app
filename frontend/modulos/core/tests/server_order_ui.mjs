// Isolated gestures and account preferences; no application accounts or network APIs.
import assert from 'node:assert/strict';
import path from 'node:path';
import os from 'node:os';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost:5187',pretendToBeVisual:true});
globalThis.BroadcastChannel=undefined;
for(const key of ['window','document','navigator','HTMLElement','HTMLInputElement','Element','MutationObserver','CustomEvent','Event'])Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true});
const server=await createServer({configFile:false,resolve:{dedupe:['react','react-dom','lucide-react']},esbuild:{jsx:'automatic',jsxImportSource:'react'},cacheDir:path.join(os.tmpdir(),'bold-server-order-ui'),optimizeDeps:{noDiscovery:true,include:[],entries:[]},server:{middlewareMode:true,hmr:false},appType:'custom'});
const load=file=>server.ssrLoadModule(`/@fs/${path.resolve(file).replaceAll('\\','/')}`);
const {default:React}=await import('react'),{createRoot}=await import('react-dom/client');
const {channelApi}=await load('../mensajeria/channel_api.js');
let person='alice',fail=false,reads=0,writes=0,selected=0,hit=null;
const orders=new Map(),groups=['A','B','C'].map((name,i)=>({id:`00000000-0000-4000-8000-${String(i+1).padStart(12,'0')}`,name,departmentId:String(i),can_edit_icon:false}));
channelApi.serverOrder=async()=>{reads++;return orders.get(person) || [];};
channelApi.saveServerOrder=async order=>{writes++;if(fail)throw Error('Sin conexión');orders.set(person,[...order]);return {slack_server_order:order};};
const {default:ServerRail}=await load('../mensajeria/server_rail.jsx');
const root=createRoot(document.getElementById('root')),homeRef=React.createRef();
const settle=(ms=35)=>new Promise(resolve=>setTimeout(resolve,ms));
const wait=async check=>{for(let i=0;i<60 && !check();i++)await settle();assert.ok(check(),'expected server order state');};
const names=()=>[...document.querySelectorAll('[data-server-id]')].map(node=>node.textContent[0]).join('');
const node=name=>[...document.querySelectorAll('[data-server-id]')].find(node=>node.textContent[0]===name);
document.elementFromPoint=()=>hit;
dom.window.HTMLElement.prototype.getBoundingClientRect=function(){const index=[...document.querySelectorAll('[data-server-id]')].indexOf(this),top=index<0 ? 0:index*60;return {left:0,right:60,top,bottom:index<0 ? 220:top+44,width:60,height:index<0 ? 220:44};};
const pointer=(target,type,pointerType,x=20,y=20)=>{const event=new dom.window.MouseEvent(type,{bubbles:true,cancelable:true,button:0,clientX:x,clientY:y});Object.defineProperties(event,{pointerId:{value:1},pointerType:{value:pointerType},isPrimary:{value:true}});target.dispatchEvent(event);};
function mount(key,disabled=false){root.render(React.createElement('section',{className:'slack_module'},React.createElement(ServerRail,{key,groups,identity:key,disabled,activeId:groups[0].id,homeRef,onSelect:()=>{selected++;},onCreate:()=>{},onChat:()=>{},onIcon:()=>{},onMore:()=>{}})));}
try{
    mount('alice');await wait(()=>names()==='ABC' && reads===1);await settle();
    pointer(node('A'),'pointerdown','mouse');await settle(190);
    assert.ok(node('A').classList.contains('is_sorting'));
    hit=node('C');pointer(window,'pointermove','mouse',20,165);await wait(()=>names()==='BCA');
    assert.equal(writes,0,'hover does not write preferences');
    pointer(window,'pointerup','mouse',20,165);await wait(()=>writes===1);
    node('A').click();assert.equal(selected,0,'the release click must not open another server');
    mount('alice-reload');await wait(()=>reads===2 && names()==='BCA');
    person='bob';mount('bob');await wait(()=>reads===3 && names()==='ABC');await settle();
    pointer(node('A'),'pointerdown','touch');pointer(window,'pointermove','touch',20,45);await settle(380);
    assert.equal(document.querySelector('.is_sorting'),null,'normal touch scrolling cancels the pending hold');
    pointer(node('C'),'pointerdown','touch',20,142);await settle(380);
    hit=node('A');pointer(window,'pointermove','touch',20,5);await wait(()=>names()==='CAB');
    pointer(window,'pointerup','touch',20,5);await wait(()=>writes===2);
    assert.notDeepEqual(orders.get('alice'),orders.get('bob'));
    await settle(420);
    node('C').dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'ArrowDown',altKey:true,bubbles:true,cancelable:true}));
    await wait(()=>writes===3 && names()==='ACB');
    pointer(node('A'),'pointerdown','mouse');await settle(190);hit=node('B');pointer(window,'pointermove','mouse',20,165);await wait(()=>names()==='CBA');
    window.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}));await wait(()=>names()==='ACB');assert.equal(writes,3);
    fail=true;node('A').dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'ArrowDown',altKey:true,bubbles:true,cancelable:true}));
    await wait(()=>writes===4 && document.querySelector('[role=alert]'));
    assert.equal(names(),'ACB','save failure restores the last confirmed order');
    await settle(420);fail=false;
    pointer(node('A'),'pointerdown','touch');await settle(380);pointer(window,'pointerup','touch');
    await wait(()=>document.querySelector('.slack_server_context'));
    assert.match(document.querySelector('.slack_server_context').textContent,/Subir servidor.*Bajar servidor/);
    assert.doesNotMatch(document.querySelector('.slack_server_context').textContent,/Cambiar imagen/,'ordering never grants icon-edit permission');
    assert.equal(writes,4,'holding without moving opens options, without saving');
    [...document.querySelectorAll('[role=menuitem]')].find(button=>button.textContent==='Bajar servidor').click();
    await wait(()=>writes===5 && names()==='CAB');
    node('A').click();
    mount('bob',true);await settle();mount('bob');await settle();node('A').click();
    assert.equal(selected,1,'temporarily locking the rail without dragging must not swallow later navigation');
    console.log('Server order UI passed: held mouse/touch drag, reload, personal isolation, scroll, keyboard, Escape, failed-save rollback and no channel navigation.');
}finally{root.unmount();await server.close();dom.window.close();}
