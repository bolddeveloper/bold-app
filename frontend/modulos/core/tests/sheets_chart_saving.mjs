import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import React,{act,useState,useRef,useEffect,useCallback,useMemo,createContext,useContext} from 'react';
import {jsx} from 'react/jsx-runtime';
import {createRoot} from 'react-dom/client';
import {patchSheetChartSaving} from '../tools/sheets_chart_saving.mjs';
const source=await readFile(new URL('../node_modules/@casualoffice/sheets/dist/sheets.js',import.meta.url),'utf8');
assert.equal(patchSheetChartSaving(source),source);
const between=(start,end)=>source.slice(source.indexOf(start),source.indexOf(end,source.indexOf(start)));
const createEmitter=new Function(between('function createEmitter()', '// src/sheets/api.ts')+';return createEmitter;')();
const createAPI=new Function('createEmitter',between('function createCasualSheetsAPI(', '// src/univer/lazy-plugins.ts')+';return createCasualSheetsAPI;')(createEmitter);
const name='__casual_sheets_charts__';
const types=['column','column-stacked','column-stacked-100','bar','bar-stacked','bar-stacked-100','line','line-stacked','area','area-stacked','pie','doughnut','scatter'];
const {readChartsFromSnapshot,writeChartsIntoSnapshot}=new Function('VALID_TYPES','CHARTS_RESOURCE_NAME',between('function migrateType(', 'var init_resources')+';return {readChartsFromSnapshot,writeChartsIntoSnapshot};')(types,name);
const pos={startRow:1,endRow:10,startColumn:3,endColumn:8};
const model={id:'chart',sheetId:'sheet',type:'bar',source:{startRow:0,endRow:2,startColumn:0,endColumn:2},pos};
const initial={id:'book',resources:[{name,data:JSON.stringify({v:1,charts:[model]})}],sheets:{sheet:{cellData:{1:{1:{v:10}}}}}};
let grid=structuredClone(initial);grid.resources=[];
let resets=0;
const engine={getActiveWorkbook:()=>({save:()=>structuredClone(grid),getId:()=>grid.id}),disposeUnit(){resets++;},createWorkbook(data){grid=structuredClone(data);}};
const api=createAPI(engine,initial.resources),events=[];
api.on('change',snapshot=>events.push(snapshot));
const {JSDOM}=await import(pathToFileURL(join(tmpdir(),'bold-ui-check/node_modules/jsdom/lib/api.js')));
const dom=new JSDOM('<div id="root"></div>');
for (const key of ['window','document','HTMLElement']) globalThis[key]=dom.window[key];
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const provider=between('function ChartsProvider(', 'var ChartsContext;'),context=createContext(null);
const dependencies={readChartsFromSnapshot,writeChartsIntoSnapshot,ChartsContext:context};
for (const name of new Set(provider.match(/use(?:State|Ref|Effect|Callback|Memo)\d*/g))) dependencies[name]=name.startsWith('useState')?useState:name.startsWith('useRef')?useRef:name.startsWith('useEffect')?useEffect:name.startsWith('useCallback')?useCallback:useMemo;
for (const name of new Set(provider.match(/jsx\d*/g))) dependencies[name]=jsx;
const Provider=new Function(...Object.keys(dependencies),provider+';return ChartsProvider;')(...Object.values(dependencies));
let controls;
function Observer(){controls=useContext(context);return null;}
const root=createRoot(document.getElementById('root'));
try {
  await act(async()=>root.render(jsx(React.StrictMode,{children:jsx(Provider,{api,children:jsx(Observer,{})})})));
  assert.equal(controls.charts[0].type,'bar','horizontal bars must not migrate to columns');
  await act(async()=>{controls.update('chart',{pos:{...pos,startRow:4,endRow:13}});controls.update('chart',{title:'Actualizado',format:{legend:'right',dataLabels:true}});});
  assert.equal(events.length,2,'StrictMode must save each explicit action exactly once');
  assert.equal(resets,0,'chart edits must retain the same workbook');
  assert.equal(readChartsFromSnapshot(api.getContent())[0].pos.startRow,4);
  const resized={startRow:4,endRow:18,startColumn:5,endColumn:14,width:625,height:375,offsetX:25,offsetY:7};
  await act(async()=>controls.update('chart',{pos:resized}));
  const persisted=JSON.parse(JSON.stringify(api.getContent()));
  const reopened=createAPI(engine,persisted.resources);
  assert.deepEqual(readChartsFromSnapshot(reopened.getContent())[0].pos,resized);
  assert.equal(readChartsFromSnapshot(reopened.getContent())[0].type,'bar');
  assert.deepEqual(readChartsFromSnapshot(reopened.getContent())[0].format,{legend:'right',dataLabels:true});
  for (const type of types) {
    await act(async()=>controls.update('chart',{type}));
    const changed=readChartsFromSnapshot(api.getContent())[0];
    assert.equal(changed.type,type);
    assert.deepEqual(changed.pos,resized,'changing type must retain exact size and position');
  }
  await act(async()=>controls.update('chart',{format:{seriesTypes:{Cantidad:'bar'},seriesColors:{Cantidad:'#4285f4'}}}));
  await act(async()=>controls.update('chart',{type:'area-stacked'}));
  assert.deepEqual(controls.charts[0].format.seriesTypes,{});
  assert.equal(controls.charts[0].format.seriesColors.Cantidad,'#4285f4');
  grid.sheets.sheet.cellData[1][1].v=20;
  await act(async()=>controls.select('chart'));
  await act(async()=>api.emit('change',api.getContent()));
  assert.equal(controls.selectedId,'chart','a save acknowledgement must retain the selected chart');
  assert.equal(controls.charts[0].pos.endColumn,14,'editing cells must retain chart size');
  assert.equal(resets,0);
  await act(async()=>controls.remove('chart'));
  assert.deepEqual(readChartsFromSnapshot(api.getContent()),[]);
  assert.deepEqual(readChartsFromSnapshot(createAPI(engine,api.getContent().resources).getContent()),[],'a deleted chart must stay deleted after reopening');
  assert.equal(resets,0);
} finally {await act(async()=>root.unmount());dom.window.close();}
