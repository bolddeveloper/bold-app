import assert from "node:assert/strict";
import {tmpdir} from "node:os";
import {join, resolve} from "node:path";
import {pathToFileURL} from "node:url";
import React, {act} from "react";
import {createRoot} from "react-dom/client";
import {createServer} from "vite";
const {JSDOM} = await import(pathToFileURL(join(tmpdir(), "bold-ui-check/node_modules/jsdom/lib/api.js")));
const dom = new JSDOM('<div id="root"></div>', {url: "http://localhost:5178"});
for (const key of ["window", "document", "HTMLElement", "Event"]) globalThis[key] = dom.window[key];
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
dom.window.HTMLElement.prototype.attachEvent = function () {};
dom.window.HTMLElement.prototype.detachEvent = function () {};
let rect = {left: 285, right: 425, top: 350, bottom: 394, width: 140, height: 44};
let nativeShows = 0;
dom.window.HTMLElement.prototype.getBoundingClientRect = () => rect;
dom.window.HTMLElement.prototype.showPopover = () => {nativeShows++;};
Object.defineProperty(dom.window.HTMLElement.prototype, "offsetHeight", {get() {return Math.min(240, parseFloat(this.style.maxHeight) || 240);}});
Object.defineProperty(window, "innerWidth", {value:320,writable:true});
Object.defineProperty(window, "innerHeight", {value:430,writable:true});
const viewport = new window.EventTarget();
Object.assign(viewport, {offsetLeft:0,offsetTop:100,width:320,height:220});
Object.defineProperty(window, "visualViewport", {value:viewport});
const server = await createServer({configFile:false,plugins:[{name:"select-icons",enforce:"pre",transform(source,id){if(id.replaceAll("\\","/").endsWith('/shared/bold_select.jsx'))return source.replace('import { Check, ChevronDown, Search, X } from "lucide-react";','const Check=()=>null,ChevronDown=Check,Search=Check,X=Check;');}}],resolve:{dedupe:["react","react-dom"]},optimizeDeps:{noDiscovery:true,entries:[],include:[]},esbuild:{jsx:"automatic"},server:{middlewareMode:true,hmr:false},appType:"custom"});
const root=createRoot(document.getElementById('root'));
try {
 const {BoldSelect}=await server.ssrLoadModule(`/@fs/${resolve('shared/bold_select.jsx').replaceAll("\\","/")}`);
 const {useDialog}=await server.ssrLoadModule(`/@fs/${resolve('shared/use_dialog.js').replaceAll("\\","/")}`);
 let parentClosed=false,selected;
 function Form(){useDialog(true,'.form',()=>{parentClosed=true;});return React.createElement('div',{className:'form'},React.createElement(BoldSelect,{label:'Persona',searchable:true,options:[{value:'a',label:'Ana'},{value:'b',label:'Un nombre muy largo'}],onValueChange:value=>{selected=value;}}));}
 await act(async()=>root.render(React.createElement(Form)));
 const click=async node=>act(async()=>node.click());
 const trigger=document.querySelector('.admin_select_trigger');
 await click(trigger);
 assert.equal(nativeShows,1);
 let panel=document.querySelector('.admin_select_menu');
 assert.equal(panel.getAttribute('popover'),'manual');
 assert.equal(panel.style.position,'fixed');
 assert.ok(parseFloat(panel.style.left)+parseFloat(panel.style.width)<=308);
 assert.ok(parseFloat(panel.style.top)>=112);
 assert.ok(parseFloat(panel.style.top)+parseFloat(panel.style.maxHeight)<=308);
 await act(async()=>panel.querySelector('input').dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape',bubbles:true})));
 assert.equal(document.querySelector('.admin_select_menu'),null);
 assert.equal(parentClosed,false,'Escape only closes the dropdown');
 assert.equal(document.activeElement,trigger);
 await click(trigger);
 await click(document.querySelectorAll('[role="option"]')[1]);
 assert.equal(selected,'b');
 assert.equal(document.querySelector('.admin_select_menu'),null);
 rect={left:0,right:140,top:110,bottom:154,width:140,height:44};
 await click(trigger);
 Object.assign(viewport,{width:240,height:160});
 await act(async()=>viewport.dispatchEvent(new Event('resize')));
 panel=document.querySelector('.admin_select_menu');
 assert.equal(panel.style.left,'12px');
 assert.ok(parseFloat(panel.style.maxHeight)<=136);
 console.log('Shared select: viewport bounds, keyboard viewport, native layer, selection, focus and nested Escape OK');
} finally {await act(async()=>root.unmount());await server.close();dom.window.close();}
